    private void jProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jProcessActionPerformed
        // TODO add your handling code here:
        try{
            double VAT = 0.15, commision = 0.05;
            String CustomerName = jTextFieldCucstomerName.getText();
            String productName =  jComboBoxSelectProduct.getSelectedItem().toString();
            double price = Integer.parseInt(jTextFieldEnterPrice.getText());
            
            double VAT_AMOUNT = (price * VAT);
            double commisionAmount = (price * commision);
            double totalPrice = price + VAT_AMOUNT + commisionAmount;
            
            JOptionPane.showMessageDialog(this, "Customer Name: "+CustomerName+
                    "\nProduct: "+productName+
                    "\nVAT: R"+VAT_AMOUNT+
                    "\nCOMMISION: R"+commisionAmount+
                    "\nTOTAL: R"+totalPrice);
            
   
            
        }catch (NumberFormatException e){
            JOptionPane.showMessageDialog(this, "ERROR, TRY AGAIN ");
        }
        
        
    }//GEN-LAST:event_jProcessActionPerformed

